/**
 * Detects the Philippine telecom provider based on the first 4 digits of a mobile number.
 */
export function detectTelcoFromPhone(phone: string): TelcoId | null {
  const clean = phone.replace(/[^0-9]/g, '');
  let prefix = '';

  if (clean.startsWith('63') && clean.length >= 6) {
    prefix = '0' + clean.slice(2, 5);
  } else if (clean.startsWith('09') && clean.length >= 4) {
    prefix = clean.slice(0, 4);
  } else if (clean.startsWith('08') && clean.length >= 4) {
    prefix = clean.slice(0, 4);
  }

  if (!prefix) return null;

  for (const telcoKey of Object.keys(TELCO_BRANDS) as TelcoId[]) {
    if (TELCO_BRANDS[telcoKey].prefixList.includes(prefix)) {
      return telcoKey;
    }
  }

  return null;
}
